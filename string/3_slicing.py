name = "prerana khairnar"
#syntax string[start point:end point]

print(name[0:6])
print(name[-8:-1])
print(name[8:])
print(name[:7])
print(name[:])  #display whole string

#syntax 2
#String[start point : end point + 1 : step/gap]

print(name[0:15:4])

#string in reverse
print(name[-1:-18:-1])
print(name[::-1])